CREATE OR REPLACE FUNCTION "public"."create_order_with_stock_update"("p_machine_id" integer, "p_machine_product_id" integer, "p_machine_command" "text", "p_slot_index" integer) RETURNS json
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$declare
  v_current_stock int;
  v_order_id int;
begin
  -- Start transaction
  -- Get current stock with lock
  select current_stock into v_current_stock
  from machine_products
  where id = p_machine_product_id
  for update;
  
  -- Check if we have stock
  if v_current_stock <= 0 then
    return json_build_object('error', 'Product out of stock');
  end if;
  
  -- Create order
  insert into orders (
    machine_id,
    machine_product_id,
    machine_command,
    status
  ) values (
    p_machine_id,
    p_machine_product_id,
    p_machine_command,
    'created'
  ) returning id into v_order_id;
  
  -- Update stock
  update machine_products
  set current_stock = current_stock - 1
  where id = p_machine_product_id;
  
  return json_build_object(
    'success', true,
    'order_id', v_order_id
  );
  
  exception when others then
    return json_build_object(
      'error', SQLERRM,
      'detail', SQLSTATE
    );
end;$$;


